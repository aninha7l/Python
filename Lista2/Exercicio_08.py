n1 = int(input("Digite o primeiro numero: "))
#solicite o primeiro numero
n2 = int(input("Digite o segundo numero: "))
#solicite o segundo numero
# soma dos dois numeros
soma = (n1) + (n2)
print ("A soma dos dois numeros e:", soma)

#Subtracao dos dois numeros
subtracao = (n1) - (n2)
print ("A subtracao dos valores e:", subtracao)

#Divisao dos dois numeros
divisao = n1/n2
print ("A divisao dos valores e:",divisao)

#Multiplicacao dos dois numeros
multiplicacao = n1 * n2
print ("A multiplicacao dos valores e:", multiplicacao)
